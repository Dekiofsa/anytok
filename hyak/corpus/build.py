def _times_from(data, bucket):
    """``{"train.jsonl.gz": t, "eval.jsonl.gz": t}`` of ``bucket`` from a map or an input/manifest.json, else None."""
    if not isinstance(data, dict):
        return None
    if data.get('kind') == 'anytok_hyak_inputs':
        data = ((data.get('provenance') or {}).get('corpus') or {}).get('gzip_mtime') or {}
    entry = data.get(bucket)
    if not isinstance(entry, dict):
        return None
    times = {name: entry.get(name) for name in GZIP_FILES}
    return times if all(isinstance(t, int) and not isinstance(t, bool) for t in times.values()) else None


def registry_path(corpus_root, size, bucket) -> Path:
    return meta_dir(corpus_root) / 'gzip-mtimes' / f'{task_key(size, bucket)}.json'


def planned_gzip_mtimes(corpus_root, size, bucket, *, test_scale=None, time_sources=(), now=None) -> dict:
    """Header times for a (re)build of one bucket and where they come from (see the module docstring)."""
    for source in list(time_sources) + [registry_path(corpus_root, size, bucket)]:
        try:
            times = _times_from(read_json(source), bucket)
        except (OSError, ValueError):
            times = None
        if times:
            return {'times': times, 'source': str(source)}
    built = int(now if now is not None else time.time())
    times = {'train.jsonl.gz': built, 'eval.jsonl.gz': built}
    source = 'build time'
    original = original_eval_times().get(bucket) if test_scale is None else None
    if original is not None:
        times['eval.jsonl.gz'] = original
        source = 'build time (train); original held-out file header time (eval)'
    return {'times': times, 'source': source}


def run_bucket(corpus_root: Path, size: str, bucket: str, *, test_scale=None, verify_only=False,
               attempts=3, backoff=ATTEMPT_BACKOFF_SECONDS, sleep=time.sleep, time_sources=(),
               env_note=None) -> tuple:
    """Build (or verify) one bucket in this process.  Returns ``(exit_code, result_dict)``.

    Writes ``.hyak/progress/<key>.json`` while building and ``.hyak/results/<key>.json`` at the end.
    ``time_sources`` are files with recorded gzip header times (:func:`planned_gzip_mtimes`);
    ``env_note`` is ``{"packages_validated": bool, "unvalidated_env_reason": str|None}`` for the manifest.
    """
    corpus_root = Path(corpus_root)
    plan = {spec['name']: spec for spec in sources.plan_for_size(size)}
    if bucket not in plan:
        raise ValueError(f'{bucket!r} is not a bucket of size {size!r}')
    spec = scaled_spec(plan[bucket], test_scale)
    root = corpus_root / f'{size}-v1'
    directory = root / bucket
    key = task_key(size, bucket)
    progress_path = meta_dir(corpus_root) / 'progress' / f'{key}.json'
    result_path = meta_dir(corpus_root) / 'results' / f'{key}.json'
    started = time.time()
    result = {'size': size, 'bucket': bucket, 'spec': spec, 'test_scale': list(test_scale) if test_scale else None,
              'started_at': utc_now(), 'host': slurm.node_name(), 'job_id': slurm.job_id(), 'pid': os.getpid(),
              'attempts': 0, 'errors': []}

    def finish(code, status, **extra):
        result.update(status=status, exit_code=code, finished_at=utc_now(),
                      seconds=round(time.time() - started, 1), **extra)
        try:
            atomic_write_json(result_path, result)
        except OSError as exc:
            print(f'[hyak corpus] WARNING: cannot write {result_path}: {exc}', file=sys.stderr, flush=True)
        try:
            progress_path.unlink()
        except OSError:
            pass
        return code, result

    lock = BucketLock(corpus_root, size, bucket)
    owner = lock.acquire()
    if owner is not None:
        who = (f'job {owner.get("job_id")} on {owner.get("host")} (pid {owner.get("pid")}, started '
               f'{owner.get("started_at")})' if 'pid' in owner else str(owner))
        print(f'[hyak corpus] {key}: locked by {who}; another process is building it. Skipping. '
              f'If that is wrong: {lock.remedy}', flush=True)
        result.update(owner=owner, lock=str(lock.path))
        return EXIT_LOCKED, dict(result, status='locked')
    if lock.took_over is not None:
        print(f'[hyak corpus] {key}: took over the stale lock of {lock.took_over}', flush=True)
    try:
        state = manifest_state(corpus_root, size, spec, test_scale)
        if state != 'missing':
            try:
                summary = verify_bucket(directory, spec, test_scale)
            except VerificationError as exc:
                message = (f'{exc}. Remedy: inspect {directory}; if it is not needed as evidence, delete that directory '
                           f'and rerun the corpus stage to rebuild the bucket (it is never rebuilt automatically)')
                print(f'[hyak corpus] {key}: existing bucket FAILED verification: {message}', flush=True)
                return finish(EXIT_FAILED, 'verify-failed', error=message)
            print(f'[hyak corpus] {key}: existing bucket verified ({summary["train"]["bytes"]:,} train bytes, '
                  f'{summary["eval"]["bytes"]:,} held-out bytes); skipping', flush=True)
            return finish(EXIT_OK, 'verified-existing', summary=summary)
        if verify_only:
            return finish(EXIT_FAILED, 'missing', error=f'{directory}/manifest.json does not exist (bucket not built)')
        extra = {'hyak': provenance()}
        extra['hyak'].update(env_note or {})
        if test_scale is not None:
            extra['test_scale'] = test_scale_marker(test_scale)
        planned = planned_gzip_mtimes(corpus_root, size, bucket, test_scale=test_scale, time_sources=time_sources)
        extra['hyak']['gzip_mtime'] = dict(planned['times'], source=planned['source'])
        print(f'[hyak corpus] {key}: gzip header times {planned["times"]} ({planned["source"]})', flush=True)
        progress_warned = []
        for attempt in range(1, attempts + 1):
            result['attempts'] = attempt
            attempt_start = time.time()

            def progress(counts, phase, attempt=attempt, attempt_start=attempt_start):
                try:
                    atomic_write_json(progress_path, {
                        'size': size, 'bucket': bucket, 'phase': phase, 'counts': counts, 'attempt': attempt,
                        'train_target': spec['train_target'], 'eval_target': spec['eval_target'],
                        'started_unix': attempt_start, 'updated_at': utc_now(), 'pid': os.getpid(),
                        'host': slurm.node_name(), 'job_id': slurm.job_id()})
                except OSError as exc:  # the dashboard row only; never abort a build for it
                    if not progress_warned:
                        progress_warned.append(True)
                        print(f'[hyak corpus] {key}: WARNING: cannot write {progress_path}: {exc}', flush=True)

            progress({k: 0 for k in ('train_bytes', 'eval_bytes', 'train_docs', 'eval_docs')}, 'starting')
            print(f'[hyak corpus] {key}: building attempt {attempt}/{attempts} '
                  f'({spec["train_target"]:,} train bytes, {spec["eval_target"]:,} held-out bytes)', flush=True)
            extra['hyak'].update(attempt=attempt, started_at=utc_now())
            try:
                with fixed_gzip_mtime(planned['times']):
                    manifest = sources.prepare_bucket(root, spec, progress=progress, extra_manifest=extra)
            except Terminated:
                raise
            except Exception as exc:  # noqa: BLE001 -- classified below
                message = redact_text(f'{type(exc).__name__}: {exc}')
                result['errors'].append({'attempt': attempt, 'error': message, 'at': utc_now(),
                                         'seconds': round(time.time() - attempt_start, 1)})
                transient = is_transient(exc)
                print(f'[hyak corpus] {key}: attempt {attempt} failed ({"transient" if transient else "permanent"}): '
                      f'{message}', flush=True)
                if transient and attempt < attempts:
                    delay = backoff * attempt
                    print(f'[hyak corpus] {key}: rebuilding from zero in {delay:.0f} s', flush=True)
                    sleep(delay)
                    continue
                return finish(EXIT_FAILED, 'failed', error=message)
            build_seconds = round(time.time() - attempt_start, 1)
            try:
                summary = verify_bucket(directory, spec, test_scale)
            except VerificationError as exc:
                print(f'[hyak corpus] {key}: freshly built bucket FAILED verification: {exc}', flush=True)
                return finish(EXIT_FAILED, 'verify-failed', error=str(exc))
            print(f'[hyak corpus] {key}: built in {build_seconds:.0f} s: {manifest["counts"]}', flush=True)
            try:
                atomic_write_json(registry_path(corpus_root, size, bucket), {
                    bucket: dict(planned['times']), 'source': planned['source'], 'recorded_at': utc_now(),
                    'sha256': manifest['files']})
            except OSError as exc:
                print(f'[hyak corpus] {key}: WARNING: cannot record the gzip header times: {exc}', flush=True)
            return finish(EXIT_OK, 'built', summary=summary, build_seconds=build_seconds)
        return finish(EXIT_FAILED, 'failed', error='no attempt left')  # pragma: no cover
    finally:
        lock.release()


def worker_main(args) -> None:
    """Child process: one bucket, then ``os._exit`` (datasets streaming can hang at interpreter exit)."""
    def handler(signum, frame):
        raise Terminated(f'signal {signum}')

    signal.signal(signal.SIGTERM, handler)
    signal.signal(signal.SIGINT, handler)
    code = EXIT_FAILED
    try:
        test_scale = parse_test_scale(args.test_scale)
        env_note = {'packages_validated': not args.allow_unvalidated_env,
                    'unvalidated_env_reason': args.allow_unvalidated_env}
        code, _ = run_bucket(Path(args.corpus_root), args.worker[0], args.worker[1], test_scale=test_scale,
                             verify_only=args.verify_only, attempts=args.attempts,
                             time_sources=[Path(p) for p in args.gzip_mtimes or []], env_note=env_note)
    except Terminated:
        print(f'[hyak corpus] {task_key(*args.worker)}: terminated; temporary files removed', flush=True)
        code = EXIT_TERMINATED
    except BaseException as exc:  # noqa: BLE001 -- report and exit non-zero
        import traceback
        traceback.print_exc()
        print(f'[hyak corpus] {task_key(*args.worker)}: worker crashed: {exc!r}', flush=True)
        code = EXIT_FAILED
    finally:
        try:
            sys.stdout.flush()
            sys.stderr.flush()
        finally:
            os._exit(code)


# --- parent: schedule children, write status -------------------------------------------------------
class Builder:
    """Runs one child per bucket (at most ``workers`` at a time) and keeps the dashboard status."""

    def __init__(self, corpus_root, tasks, *, workers, test_scale=None, verify_only=False, attempts=3,
                 writer=None, min_remaining_seconds=0.0, child_python=None, repo=None, poll_seconds=2.0,
                 time_sources=(), unvalidated_env_reason=None):
        self.corpus_root = Path(corpus_root)
        self.tasks = sorted(tasks, key=lambda t: -t[1]['train_target'])  # largest first; content is order-independent
        self.order = [spec['name'] for _, spec in tasks]
        self.workers = max(1, int(workers))
        self.test_scale = test_scale
        self.verify_only = verify_only
        self.attempts = attempts
        self.writer = writer
        self.min_remaining = min_remaining_seconds
        self.python = child_python or sys.executable
        self.repo = Path(repo) if repo else repo_root()
        self.poll = poll_seconds
        self.time_sources = [str(p) for p in time_sources]
        self.unvalidated_env_reason = unvalidated_env_reason
        self.running = {}      # key -> (Popen, size, spec, started, log handle)
        self.outcome = {}      # bucket -> result dict
        self.terminating = False
        self.not_started = []
        self.last_status = 0.0

    # child process ---------------------------------------------------------------------------------
    def command(self, size, bucket):
        command = [self.python, '-m', 'hyak.corpus.build', '--worker', size, bucket,
                   '--corpus-root', str(self.corpus_root), '--attempts', str(self.attempts)]
        if self.test_scale is not None:
            command += ['--test-scale', f'{self.test_scale[0]}:{self.test_scale[1]}']
        if self.verify_only:
            command.append('--verify-only')
        for source in self.time_sources:
            command += ['--gzip-mtimes', source]
        if self.unvalidated_env_reason:
            command += ['--allow-unvalidated-env', self.unvalidated_env_reason]
        return command

    def spawn(self, size, bucket):
        logs = meta_dir(self.corpus_root) / 'logs'
        logs.mkdir(parents=True, exist_ok=True)
        log_path = logs / f'{task_key(size, bucket)}.log'
        handle = open(log_path, 'ab')
        handle.write(f'\n===== {utc_now()} job {slurm.worker_id()} on {slurm.node_name()} =====\n'.encode())
        handle.flush()
        env = dict(os.environ)
        env['PYTHONPATH'] = str(self.repo) + (os.pathsep + env['PYTHONPATH'] if env.get('PYTHONPATH') else '')
        env.setdefault('PYTHONUNBUFFERED', '1')
        process = subprocess.Popen(self.command(size, bucket), stdout=handle, stderr=subprocess.STDOUT,
                                   cwd=str(self.repo), env=env, start_new_session=True)
        return process, handle, log_path

    # status ----------------------------------------------------------------------------------------
    def bucket_rows(self):
        rows = {}
        for size, spec in sources.bucket_specs().values():
            spec = scaled_spec(spec, self.test_scale)
            name = spec['name']
            row = {'size': size, 'train_target': spec['train_target'], 'eval_target': spec['eval_target']}
            outcome = self.outcome.get(name)
            if outcome is not None:
                row['state'] = outcome.get('status')
                summary = outcome.get('summary') or {}
                if summary:
                    row['train_bytes'] = summary['train']['bytes']
                    row['eval_bytes'] = summary['eval']['bytes']
                    row['train_docs'] = summary['train']['documents']
                    row['eval_docs'] = summary['eval']['documents']
                if outcome.get('seconds') is not None:
                    row['seconds'] = outcome['seconds']
            elif any(running_spec['name'] == name for _p, _s, running_spec, *_rest in self.running.values()):
                row['state'] = 'running'
                progress = self.read_progress(size, name)
                if progress:
                    row['train_bytes'] = progress['counts'].get('train_bytes', 0)
                    row['eval_bytes'] = progress['counts'].get('eval_bytes', 0)
            else:
                row['state'] = ('complete' if manifest_state(self.corpus_root, size, spec, self.test_scale) == 'complete'
                                else 'pending')
            rows[name] = row
        return rows

    def read_progress(self, size, bucket):
        try:
            return read_json(meta_dir(self.corpus_root) / 'progress' / f'{task_key(size, bucket)}.json')
        except (OSError, ValueError):
            return None

    def completed(self, rows=None):
        rows = rows or self.bucket_rows()
        return sum(row['state'] in ('complete', 'built', 'verified-existing') for row in rows.values())

    def write_status(self, state=None, stage=None, error=None, force=False):
        if self.writer is None:
            return None
        now = time.monotonic()
        if not force and now - self.last_status < STATUS_SECONDS:
            return None
        self.last_status = now
        rows = self.bucket_rows()
        workers = []
        for key, (process, size, spec, started, _handle, _log) in sorted(self.running.items()):
            progress = self.read_progress(size, spec['name']) or {}
            counts = progress.get('counts', {})
            train, eval_ = counts.get('train_bytes', 0), counts.get('eval_bytes', 0)
            elapsed = time.time() - progress.get('started_unix', started)
            eta = None
            if train > 0 and elapsed > 30 and progress.get('phase') == 'train':
                eta = round(max(0.0, (spec['train_target'] - train) / (train / elapsed)), 0)
            task = (f'{spec["name"]}: {train / 1e6:,.1f}/{spec["train_target"] / 1e6:,.1f} MB train, '
                    f'{eval_ / 1e6:,.2f}/{spec["eval_target"] / 1e6:,.2f} MB held-out'
                    + (f' (attempt {progress["attempt"]})' if progress.get('attempt', 1) > 1 else ''))
            workers.append(self.writer.worker_row(task=task, suffix=spec['name'], eta_seconds=eta,
                                                  state='Verifying' if self.verify_only else 'Building'))
        done = self.completed(rows)
        if state is None:
            state = 'running'
        if stage is None:
            stage = ('verifying' if self.verify_only else 'building') if state == 'running' else None
        extra = {'buckets': rows, 'corpus_root': str(self.corpus_root),
                 'test_scale': list(self.test_scale) if self.test_scale else None}
        return self.writer.update(done, stage=stage, state=state, workers=workers if state == 'running' else [],
                                  error=error, **extra)

    # main loop -------------------------------------------------------------------------------------
    def _on_signal(self, signum, frame):
        if not self.terminating:
            print(f'[hyak corpus] received signal {signum}: stopping all bucket workers', flush=True)
        self.terminating = True

    def time_left(self):
        remaining = slurm.seconds_remaining(default=float('inf'))
        return float('inf') if remaining is None else remaining

    def run(self) -> int:
        previous = {sig: signal.signal(sig, self._on_signal) for sig in (signal.SIGTERM, signal.SIGINT)}
        try:
            return self._run()
        finally:
            for sig, handler in previous.items():
                signal.signal(sig, handler)

    def _run(self) -> int:
        queue = list(self.tasks)
        self.write_status(force=True)
        while queue or self.running:
            if self.terminating:
                self.stop_children()
                break
            # A verify-only child only re-reads files (minutes for the largest bucket): a short guard suffices.
            guard = min(self.min_remaining, 600.0) if self.verify_only else self.min_remaining
            while queue and len(self.running) < self.workers and not self.terminating:
                if self.time_left() < guard:
                    self.not_started = [spec['name'] for _, spec in queue]
                    print(f'[hyak corpus] less than {guard / 60:.0f} min left in this job: not starting '
                          f'{", ".join(self.not_started)}; resubmit to continue', flush=True)
                    queue = []
                    break
                size, spec = queue.pop(0)
                process, handle, log_path = self.spawn(size, spec['name'])
                self.running[task_key(size, spec['name'])] = (process, size, spec, time.time(), handle, log_path)
                print(f'[hyak corpus] started {size}/{spec["name"]} (pid {process.pid}, log {log_path})', flush=True)
            self.reap()
            self.write_status()
            if self.running:
                time.sleep(self.poll)
        self.reap()
        return self.finish()

    def reap(self):
        for key, (process, size, spec, started, handle, log_path) in list(self.running.items()):
            code = process.poll()
            if code is None:
                continue
            handle.close()
            del self.running[key]
            try:
                result = read_json(meta_dir(self.corpus_root) / 'results' / f'{key}.json')
                if result.get('started_at') and result.get('pid') != process.pid:
                    result = None  # a stale result file of an earlier child
            except (OSError, ValueError):
                result = None
            if result is None or code == EXIT_LOCKED:
                status = {EXIT_LOCKED: 'locked', EXIT_TERMINATED: 'terminated'}.get(code, 'failed')
                result = {'status': status, 'exit_code': code, 'seconds': round(time.time() - started, 1),
                          'error': f'worker exited with code {code}; see {log_path}'}
            self.outcome[spec['name']] = result
            line = f'[hyak corpus] {size}/{spec["name"]}: {result.get("status")} (exit {code})'
            if code not in (EXIT_OK,):
                tail = ' | '.join(row.strip() for row in tail_lines(log_path, 8) if row.strip())
                line += f'; log {log_path}: {redact_text(tail)}'
            print(line, flush=True)
            if self.writer is not None:
                self.writer.event({'event': 'bucket_end', 'bucket': spec['name'], 'size': size,
                                   'status': result.get('status'), 'exit_code': code,
                                   'seconds': result.get('seconds'), 'error': result.get('error'),
                                   'counts': (result.get('summary') or {}).get('counts')})
                self.write_status(force=True)

    def stop_children(self):
        for process, *_ in self.running.values():
            try:
                os.killpg(process.pid, signal.SIGTERM)
            except OSError:
                pass
        deadline = time.time() + TERM_GRACE_SECONDS
        while self.running and time.time() < deadline:
            self.reap()
            time.sleep(0.5)
        for process, *_ in self.running.values():
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except OSError:
                pass
        while self.running:
            self.reap()
            time.sleep(0.2)

    def write_summaries(self):
        """Write ``<size>-v1/summary.json`` (original format) for every size whose buckets are all complete."""
        written = []
        for size in sources.POOL_SIZES:
            specs = [scaled_spec(spec, self.test_scale) for spec in sources.plan_for_size(size)]
            if not all(manifest_state(self.corpus_root, size, spec, self.test_scale) == 'complete' for spec in specs):
                continue
            manifests = [read_json(self.corpus_root / f'{size}-v1' / spec['name'] / 'manifest.json') for spec in specs]
            path = self.corpus_root / f'{size}-v1' / 'summary.json'
            text = sources.summary_text(size, manifests)
            try:
                current = path.read_text(encoding='utf-8')
            except FileNotFoundError:
                current = None
            if current != text:
                atomic_write_text(path, text)
            written.append(size)
        return written

    def check_summaries(self):
        """Verify-only counterpart of :meth:`write_summaries`: summary.json must equal the manifests' totals."""
        problems, checked = [], []
        for size in sources.POOL_SIZES:
            specs = [scaled_spec(spec, self.test_scale) for spec in sources.plan_for_size(size)]
            if not all(manifest_state(self.corpus_root, size, spec, self.test_scale) == 'complete' for spec in specs):
                continue
            manifests = [read_json(self.corpus_root / f'{size}-v1' / spec['name'] / 'manifest.json') for spec in specs]
            path = self.corpus_root / f'{size}-v1' / 'summary.json'
            try:
                current = path.read_text(encoding='utf-8')
            except FileNotFoundError:
                current = None
            if current != sources.summary_text(size, manifests):
                problems.append(f'{path} is missing or does not match the bucket manifests (run a build to rewrite it)')
            checked.append(size)
        return checked, problems

    def finish(self) -> int:
        problems = []
        if self.verify_only:
            summaries, problems = self.check_summaries()
        else:
            summaries = self.write_summaries()
        rows = self.bucket_rows()
        done = self.completed(rows)
        good = ('built', 'verified-existing')
        failed = sorted(name for name, r in self.outcome.items() if r.get('status') not in good + ('locked',))
        locked = sorted(name for name, r in self.outcome.items() if r.get('status') == 'locked')
        print(f'[hyak corpus] {done}/23 buckets complete; summaries {"checked" if self.verify_only else "written"} '
              f'for: {", ".join(summaries) or "none"}', flush=True)
        if self.terminating:
            self.write_status(state='stopped', stage='stopped', force=True,
                              error='stopped by a signal; resubmit the corpus stage to continue (complete buckets are kept)')
            return EXIT_TERMINATED
        if failed or problems:
            details = '; '.join([f'{name}: {self.outcome[name].get("status")} '
                                 f'({str(self.outcome[name].get("error", ""))[:300]})' for name in failed] + problems)
            self.write_status(state='failed', stage='failed', force=True, error=redact_text(details))
            print(f'[hyak corpus] FAILED: {details}', flush=True)
            return EXIT_FAILED
        if done == 23 and not locked and not self.not_started:
            self.write_status(state='complete', stage='complete', force=True)
            return EXIT_OK
        notes = []
        if self.not_started:
            notes.append(f'not started because of the job time limit: {", ".join(self.not_started)}'
                         + (' (nothing was verified for them)' if self.verify_only else ''))
        if locked:
            sizes = {spec['name']: size for size, spec in self.tasks}
            paths = [str(meta_dir(self.corpus_root) / 'locks' / task_key(sizes.get(name, '?'), name)) for name in locked]
            notes.append(f'locked by another process: {", ".join(locked)} (lock directories {", ".join(paths)}; if no '
                         f'corpus build runs anywhere -- squeue -u $USER, ps -u $USER on both login nodes -- remove them '
                         f'and resubmit)')
        notes.append(f'{done}/23 buckets complete; submit another corpus job for the rest')
        self.write_status(state='paused', stage='paused', force=True, error='; '.join(notes))
        print(f'[hyak corpus] paused: {"; ".join(notes)}', flush=True)
        return EXIT_OK


# --- probe ------------------------------------------------------------------------------------------
def run_probe(size_list, writer=None, output=None) -> int:
    """First record of each source kind (port of probe_sources, but every source is tried)."""
    results, failures = {}, 0
    selection = []
    for size in size_list:
        for spec in sources.probe_selection(size):
            if spec['name'] not in {s['name'] for s in selection}:
                selection.append(spec)
    # Fast failure without network: two short attempts per request instead of five with minutes of backoff.
    saved = (sources.OPEN_ATTEMPTS, sources.OPEN_BACKOFF_SECONDS)
    sources.OPEN_ATTEMPTS, sources.OPEN_BACKOFF_SECONDS = 2, 5.0
    try:
        return _probe(selection, writer, output)
    finally:
        sources.OPEN_ATTEMPTS, sources.OPEN_BACKOFF_SECONDS = saved


def _probe(selection, writer, output) -> int:
    results, failures = {}, 0
    for spec in selection:
        start = time.time()
        try:
            row = sources.probe_one(spec)
            row['seconds'] = round(time.time() - start, 1)
            print(f'Probed {spec["name"]}: {row["bytes"]} bytes, id {row["id"]!r} ({row["seconds"]} s)', flush=True)
        except Exception as exc:  # noqa: BLE001 -- diagnostics: report every source
            failures += 1
            row = {'error': redact_text(f'{type(exc).__name__}: {exc}'), 'seconds': round(time.time() - start, 1)}
            print(f'Probe FAILED for {spec["name"]}: {row["error"]}', flush=True)
        repo = sources.source_info(spec)[0]
        row.update(dataset=repo, revision=sources.SOURCE_REVISIONS[repo])
        results[spec['name']] = row
    report = {'at_utc': utc_now(), 'host': slurm.node_name(), 'job_id': slurm.job_id(),
              'packages': package_versions(), 'python': sys.version.split()[0], 'results': results,
              'failures': failures}
    if output is not None:
        atomic_write_json(output, report)
        print(f'[hyak corpus] probe report: {output}', flush=True)
    if writer is not None:
        writer.event({'event': 'probe', 'failures': failures, 'results': results})
    print(json.dumps(results, indent=2, ensure_ascii=False))
    if failures:
        print(f'[hyak corpus] {failures} source(s) cannot be read from this node. Remedy: check outbound HTTPS to '
              f'huggingface.co (compute nodes may have none: hyak/README.md section 13), HF_TOKEN for gated data',
              file=sys.stderr, flush=True)
    return EXIT_OK if failures == 0 else EXIT_USAGE


# --- command line -------------------------------------------------------------------------------------
def parse_args(argv=None):
    parser = argparse.ArgumentParser(prog='python -m hyak.corpus.build', description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--sizes', nargs='+', choices=sources.POOL_SIZES, default=list(sources.POOL_SIZES),
                        help='pool sizes to build (default: all three)')
    parser.add_argument('--buckets', nargs='+', metavar='BUCKET', help='only these buckets (of the chosen sizes)')
    parser.add_argument('--workers', type=int, help='parallel bucket processes (default HYAK_CORPUS_WORKERS)')
    parser.add_argument('--attempts', type=int, default=3,
                        help='attempts per bucket for transient errors, each from zero (default 3)')
    parser.add_argument('--probe', action='store_true', help='only probe the first record of every source')
    parser.add_argument('--verify-only', action='store_true', help='only verify built buckets (no downloads)')
    parser.add_argument('--corpus-root', type=Path, help='default: $ANYTOK_ROOT/corpus')
    parser.add_argument('--monitor-dir', type=Path, help='status directory (default: the corpus stage monitor dir)')
    parser.add_argument('--min-remaining-minutes', type=float, default=60.0,
                        help='do not start a bucket when the Slurm job has less time left (default 60)')
    parser.add_argument('--test-scale', metavar='TRAIN_BYTES:EVAL_BYTES',
                        help='TEST ONLY: tiny byte targets, manifests marked non-production; needs --corpus-root '
                             'outside $ANYTOK_ROOT/corpus')
    parser.add_argument('--allow-unvalidated-env', metavar='REASON',
                        help='build with package versions other than VALIDATED_PACKAGES; the reason is recorded '
                             'in every manifest (needs the user\'s approval: the corpus may then differ)')
    parser.add_argument('--gzip-mtimes', action='append', metavar='FILE',
                        help='recorded gzip header times to reuse (a {bucket: {train.jsonl.gz, eval.jsonl.gz}} map '
                             'or an input/manifest.json); default: $ANYTOK_ROOT/input/manifest.json for the '
                             'production corpus root, then the corpus root\'s own record')
    parser.add_argument('--config', type=Path, help='config file (default $HYAK_CONFIG or hyak/config.env)')
    parser.add_argument('--worker', nargs=2, metavar=('SIZE', 'BUCKET'), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    if args.attempts < 1:
        parser.error('--attempts must be >= 1')
    if args.worker and not args.corpus_root:
        parser.error('--worker needs --corpus-root')
    if args.allow_unvalidated_env is not None and not args.allow_unvalidated_env.strip():
        parser.error('--allow-unvalidated-env needs a reason')
    return args


def _check_data_env():
    missing = []
    for name in ('datasets', 'requests'):
        try:
            importlib.import_module(name)
        except Exception as exc:  # noqa: BLE001
            missing.append(f'{name} ({exc})')
    if missing:
        raise ConfigError('cannot import ' + ', '.join(missing) + '. Remedy: run inside the data environment '
                          '(hyak_activate data; setup: hyak/env/setup_data_env.sh)')


def main(argv=None) -> int:
    args = parse_args(argv)
    if args.worker:
        worker_main(args)  # never returns
    try:
        test_scale = parse_test_scale(args.test_scale)
        cfg = load_config(args.config)
        paths = Paths.from_config(cfg)
        production_root = paths.corpus_root
        corpus_root = Path(os.path.normpath(str(args.corpus_root))) if args.corpus_root else production_root
        if not corpus_root.is_absolute():
            raise ConfigError(f'--corpus-root must be absolute, got {corpus_root}')
        if test_scale is not None and (args.corpus_root is None or corpus_root == production_root
                                       or production_root in corpus_root.parents):
            raise ConfigError(f'--test-scale builds must go to a separate --corpus-root outside {production_root}')
        tasks = selected_tasks(args.sizes, args.buckets, test_scale)
        workers = args.workers if args.workers is not None else int(cfg['HYAK_CORPUS_WORKERS'])
        if workers < 1:
            raise ConfigError('--workers must be >= 1')
        if not os.environ.get('HF_HOME'):
            os.environ['HF_HOME'] = str(paths.hf_cache)  # keep the Hugging Face cache on project storage
        if cfg.get('HF_TOKEN') and not os.environ.get('HF_TOKEN'):
            os.environ['HF_TOKEN'] = cfg['HF_TOKEN']
        if not args.verify_only:
            _check_data_env()
        unvalidated = package_problems() if not (args.verify_only or args.probe) and test_scale is None else []
        if unvalidated and not args.allow_unvalidated_env:
            raise ConfigError('the data environment differs from the validated package set: ' + '; '.join(unvalidated)
                              + '. Remedy: recreate it with hyak/env/setup_data_env.sh (it installs exactly that set). '
                              'Building with other versions may change the corpus and needs the user\'s approval; '
                              'then pass --allow-unvalidated-env "<reason>" (recorded in every manifest)')
        time_sources = [Path(p) for p in args.gzip_mtimes or []]
        if corpus_root == production_root and paths.input_manifest not in time_sources:
            time_sources.append(paths.input_manifest)
    except (ConfigError, ValueError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        return EXIT_USAGE
    from hyak.common.status import StatusWriter
    meta = STAGE_PROGRESS[STAGE_CORPUS]
    writer = StatusWriter(STAGE_CORPUS, meta['total'], meta['unit'], meta['completed_field'], cfg=cfg,
                          monitor_dir=args.monitor_dir)
    if args.probe:
        output = (args.monitor_dir or paths.monitor_dir(STAGE_CORPUS)) / 'probe.json'
        return run_probe(args.sizes, writer=writer, output=output)
    corpus_root.mkdir(parents=True, exist_ok=True)
    try:
        free = os.statvfs(corpus_root).f_bavail * os.statvfs(corpus_root).f_frsize
        if test_scale is None and free < MIN_FREE_BYTES:
            print(f'[hyak corpus] WARNING: only {free / 1024 ** 3:.1f} GiB free on {corpus_root}; '
                  f'the full corpus needs about 5 GiB', flush=True)
    except OSError:
        pass
    print(f'[hyak corpus] corpus root {corpus_root}; {len(tasks)} bucket(s); {workers} worker(s); '
          f'HF_HOME={os.environ.get("HF_HOME")}; packages {package_versions()}'
          + (f'; TEST SCALE {test_scale}' if test_scale else ''), flush=True)
    if unvalidated:
        print(f'[hyak corpus] WARNING: building with an unvalidated data environment ({"; ".join(unvalidated)}); '
              f'reason recorded: {args.allow_unvalidated_env}', flush=True)
    writer.event({'event': 'build_start', 'buckets': [spec['name'] for _, spec in tasks], 'workers': workers,
                  'corpus_root': str(corpus_root), 'test_scale': list(test_scale) if test_scale else None,
                  'verify_only': bool(args.verify_only), 'packages': package_versions(),
                  'packages_validated': not unvalidated, 'unvalidated_env_reason': args.allow_unvalidated_env,
                  'host': socket.gethostname()})
    builder = Builder(corpus_root, tasks, workers=workers, test_scale=test_scale, verify_only=args.verify_only,
                      attempts=args.attempts, writer=writer, min_remaining_seconds=args.min_remaining_minutes * 60,
                      time_sources=time_sources, unvalidated_env_reason=args.allow_unvalidated_env)
    return builder.run()


if __name__ == '__main__':
    _code = main()
    sys.stdout.flush()
    sys.stderr.flush()
    # os._exit: the datasets/pyarrow stack can block in interpreter finalisation after streaming.
    os._exit(_code)
