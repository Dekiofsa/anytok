# --- small helpers ------------------------------------------------------------------------------
def task_key(size: str, bucket: str) -> str:
    return f'{size}__{bucket}'


def meta_dir(corpus_root: Path) -> Path:
    """``<corpus root>/.hyak`` (locks, progress, results, logs of the build)."""
    return Path(corpus_root) / '.hyak'


def parse_test_scale(text):
    """``'200000:50000'`` -> ``(200000, 50000)``; both must be positive."""
    if text is None:
        return None
    match = _TEST_SCALE_RE.fullmatch(text.strip())
    if not match or int(match.group(1)) < 1 or int(match.group(2)) < 1:
        raise ValueError(f'--test-scale expects TRAIN_BYTES:EVAL_BYTES with positive integers, got {text!r}')
    return int(match.group(1)), int(match.group(2))


def scaled_spec(spec: dict, test_scale) -> dict:
    """The spec to build: the original one, or a copy with the test-scale byte targets."""
    spec = dict(spec)
    if test_scale is not None:
        spec['train_target'], spec['eval_target'] = test_scale
    return spec


def test_scale_marker(test_scale) -> dict:
    """Top-level manifest key of a test-scale bucket (marks it non-production)."""
    return {'production': False, 'train_target': test_scale[0], 'eval_target': test_scale[1],
            'note': 'test-scale miniature built with hyak.corpus.build --test-scale; never use for training'}


def selected_tasks(sizes, buckets, test_scale=None):
    """``[(size, spec), ...]`` in build order for the requested sizes and bucket names."""
    sizes = list(sizes or sources.POOL_SIZES)
    for size in sizes:
        if size not in sources.POOL_SIZES:
            raise ValueError(f'Unknown size {size!r}; expected some of {", ".join(sources.POOL_SIZES)}')
    tasks = [(size, scaled_spec(spec, test_scale)) for size in sources.POOL_SIZES if size in sizes
             for spec in sources.plan_for_size(size)]
    if buckets:
        names = {spec['name'] for _, spec in tasks}
        unknown = [b for b in buckets if b not in names]
        if unknown:
            raise ValueError(f'Bucket(s) {", ".join(unknown)} are not in sizes {", ".join(sizes)}; '
                             f'known: {", ".join(sorted(names))}')
        tasks = [(size, spec) for size, spec in tasks if spec['name'] in set(buckets)]
    return tasks


def package_versions() -> dict:
    """Installed versions of RECORDED_PACKAGES (None when a distribution is not installed)."""
    from importlib import metadata
    versions = {}
    for name in RECORDED_PACKAGES:
        try:
            versions[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            versions[name] = None
    return versions


def provenance() -> dict:
    """``hyak`` manifest block: who built the bucket with what (no effect on content)."""
    module = Path(sources.__file__)
    return {
        'builder': 'hyak.corpus.build',
        'port_of': sources.ORIGINAL_SOURCE,
        'port_of_sha256': sources.ORIGINAL_SOURCE_SHA256,
        'sources_module_sha256': hashlib.sha256(module.read_bytes()).hexdigest(),
        'python': sys.version.split()[0],
        'packages': package_versions(),
        'zlib': {'version': zlib.ZLIB_VERSION, 'runtime': zlib.ZLIB_RUNTIME_VERSION},
        'host': slurm.node_name(),
        'job_id': slurm.job_id(),
        'hf_token_used': bool(os.environ.get('HF_TOKEN', '').strip()),
    }


def package_problems(versions=None) -> list:
    """Differences between the installed RECORDED_PACKAGES and VALIDATED_PACKAGES (empty list = validated)."""
    versions = package_versions() if versions is None else versions
    return [f'{name} {versions.get(name) or "not installed"} (validated: {wanted})'
            for name, wanted in VALIDATED_PACKAGES.items() if versions.get(name) != wanted]


def is_transient(exc: BaseException) -> bool:
    """Whether rebuilding the bucket from zero may succeed (network or download corruption)."""
    seen = set()
    chain = exc
    while chain is not None and id(chain) not in seen:
        seen.add(id(chain))
        if isinstance(chain, (sources.SourceUnavailable, VerificationError, UnicodeError, Terminated)):
            return False
        if isinstance(chain, OSError) and chain.errno in PERMANENT_ERRNOS:
            return False  # disk full, quota exceeded, read-only or forbidden: a rebuild cannot help
        chain = chain.__cause__ or chain.__context__
    if isinstance(exc, RuntimeError) and ('Source exhausted' in str(exc) or 'different settings' in str(exc)):
        return False
    if isinstance(exc, (OSError, EOFError, zlib.error, TimeoutError, ConnectionError, json.JSONDecodeError)):
        return True
    root = type(exc).__module__.split('.')[0]
    return root in {'requests', 'urllib3', 'fsspec', 'aiohttp', 'huggingface_hub', 'httpx', 'httpx2',
                    'httpcore', 'httpcore2', 'hf_xet', 'datasets', 'pyarrow'}


# --- bucket verification -------------------------------------------------------------------------
def manifest_state(corpus_root: Path, size: str, spec: dict, test_scale=None):
    """``'complete'`` if ``manifest.json`` exists with this spec and revision, ``'missing'``, or ``'foreign'``."""
    path = Path(corpus_root) / f'{size}-v1' / spec['name'] / 'manifest.json'
    try:
        manifest = read_json(path)
    except FileNotFoundError:
        return 'missing'
    except (OSError, ValueError):
        return 'foreign'
    repo = sources.source_info(spec)[0]
    if (manifest.get('spec') != spec or manifest.get('revision') != sources.SOURCE_REVISIONS[repo]
            or (manifest.get('test_scale') is not None) != (test_scale is not None)):
        return 'foreign'
    return 'complete'


def verify_bucket(directory: Path, spec: dict, test_scale=None) -> dict:
    """Re-check a built bucket against everything the builder guarantees; raises VerificationError.

    Checks: manifest keys/spec/revision/dataset/config/split policy; the test-scale marker;
    file SHA-256 (as the original ``verify_corpus``); a recount of documents and raw bytes (as
    ``verify_corpus``); every line is ``{"id": str, "text": str}`` with keys in that order and a
    non-empty id; every text has 100..1,000,000 UTF-8 bytes; both byte targets are reached and
    the last document of each file is the one that crossed the target; for hash-held-out buckets
    every held-out id satisfies ``held_out(split key)`` and no train id does.  Returns a summary
    with counts, first ids and duplicate/overlap statistics (reported, not errors).
    """
    directory = Path(directory)
    path = directory / 'manifest.json'
    try:
        manifest = read_json(path)
    except (OSError, ValueError) as exc:
        raise VerificationError(f'{path}: unreadable manifest ({exc})') from exc
    repo, config, policy = sources.source_info(spec)
    for key, expected in (('spec', spec), ('dataset', repo), ('config', config),
                          ('revision', sources.SOURCE_REVISIONS[repo]), ('split_policy', policy)):
        if manifest.get(key) != expected:
            raise VerificationError(f'{path}: {key} is {manifest.get(key)!r}, expected {expected!r}')
    marker = manifest.get('test_scale')
    if test_scale is None and marker is not None:
        raise VerificationError(f'{path}: this is a test-scale bucket ({marker}); production needs a full build. '
                                f'Remedy: delete {directory} and rebuild without --test-scale')
    if test_scale is not None and marker != test_scale_marker(test_scale):
        raise VerificationError(f'{path}: test-scale marker {marker!r} does not match --test-scale {test_scale}')
    counts = manifest.get('counts') or {}
    hash_policy = policy not in sources.SEPARATE_EVAL_POLICIES
    summary = {'bucket': spec['name'], 'split_policy': policy}
    eval_ids = {}
    for split in ('eval', 'train'):
        file = directory / f'{split}.jsonl.gz'
        if not file.is_file():
            raise VerificationError(f'{file} is missing although {path} exists')
        digest = sources._sha256(file)
        if digest != (manifest.get('files') or {}).get(f'{split}.jsonl.gz'):
            raise VerificationError(f'Checksum mismatch: {file} (sha256 {digest}); the file changed after it was built. '
                                    f'Remedy: delete {directory} and rebuild the bucket')
        total = docs = last = 0
        first_id = None
        duplicates = overlap = 0
        seen = set() if split == 'eval' else None
        with gzip.open(file, 'rt', encoding='utf-8') as handle:
            for number, line in enumerate(handle, 1):
                try:
                    record = json.loads(line)
                except ValueError as exc:
                    raise VerificationError(f'{file}:{number}: not JSON ({exc})') from exc
                if not isinstance(record, dict) or list(record) != ['id', 'text']:
                    raise VerificationError(f'{file}:{number}: record must be {{"id", "text"}} in that order')
                identifier, text = record['id'], record['text']
                if not isinstance(identifier, str) or not identifier or not isinstance(text, str):
                    raise VerificationError(f'{file}:{number}: id must be a non-empty string and text a string')
                size = len(text.encode('utf-8'))
                if size < 100 or size > sources.MAX_DOCUMENT_BYTES:
                    raise VerificationError(f'{file}:{number}: text has {size} bytes, outside 100..{sources.MAX_DOCUMENT_BYTES}')
                if hash_policy:
                    key = sources.split_key_of(spec['kind'], identifier)
                    if sources.held_out(key) != (split == 'eval'):
                        raise VerificationError(f'{file}:{number}: id {identifier!r} is on the wrong side of the held-out rule')
                if split == 'eval':
                    if identifier in seen:
                        duplicates += 1
                    seen.add(identifier)
                elif identifier in eval_ids:
                    overlap += 1
                if first_id is None:
                    first_id = identifier
                total += size
                docs += 1
                last = size
        if total != counts.get(f'{split}_bytes') or docs != counts.get(f'{split}_docs'):
            raise VerificationError(f'Manifest count mismatch: {file} has {docs} documents / {total} bytes, '
                                    f'manifest says {counts.get(f"{split}_docs")} / {counts.get(f"{split}_bytes")}')
        target = spec[f'{split}_target']
        if total < target:
            raise VerificationError(f'{file}: {total} bytes, below the target {target}')
        if total - last >= target:
            raise VerificationError(f'{file}: the target {target} was already reached before the last document '
                                    f'({total - last} bytes); the stopping rule of prepare_bucket was not followed')
        summary[split] = {'documents': docs, 'bytes': total, 'first_id': first_id, 'last_document_bytes': last,
                          'compressed_bytes': file.stat().st_size, 'sha256': digest}
        if split == 'eval':
            summary[split]['duplicate_ids'] = duplicates
            eval_ids = seen
        else:
            summary[split]['ids_also_in_eval'] = overlap
    summary['counts'] = counts
    return summary


# --- one bucket (child process body; in-process callable for tests) ------------------------------
def _pid_alive(pid) -> bool:
    if not isinstance(pid, int) or pid <= 0:
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except OSError:
        return True  # exists, owned by someone else
    return True


class BucketLock:
    """Atomic ``mkdir`` lock ``<corpus root>/.hyak/locks/<size>__<bucket>`` with an owner file.

    The owner refreshes the modification time of ``owner.json`` every ``LOCK_HEARTBEAT_SECONDS``.
    A lock is stale when its owner process is gone (same host: pid check, for every kind of job id),
    when Slurm no longer knows the owner job, or, when neither can be checked (another host, no Slurm
    answer), when the heartbeat is older than ``LOCK_STALE_SECONDS``.  A stale lock is never renamed
    or deleted: the taker creates ``<lock>/takeover`` atomically (one contender wins), re-reads the
    owner under that marker and only then writes its own ``owner.json``.  ``release`` removes the
    lock only while ``owner.json`` still names this process.
    """

    def __init__(self, corpus_root: Path, size: str, bucket: str):
        self.path = meta_dir(corpus_root) / 'locks' / task_key(size, bucket)
        self.owner = {'job_id': slurm.worker_id(), 'host': slurm.node_name(), 'pid': os.getpid(),
                      'started_at': utc_now(), 'started_unix': time.time()}
        self.held = False
        self.took_over = None
        self._beat_stop = None

    @property
    def remedy(self) -> str:
        return (f'lock directory {self.path}: if no corpus build runs anywhere (squeue -u $USER; ps -u $USER on both '
                f'login nodes), remove it (rm -r {self.path}) and rerun')

    def _read_owner(self):
        try:
            return read_json(self.path / 'owner.json')
        except (OSError, ValueError):
            return None

    def _heartbeat_age(self, owner) -> float:
        try:
            beat = (self.path / 'owner.json').stat().st_mtime
        except OSError:
            beat = 0.0
        return time.time() - max(beat, float(owner.get('started_unix', 0) or 0))

    def _stale(self, owner) -> bool:
        if owner is None:
            try:
                age = time.time() - self.path.stat().st_mtime
            except OSError:
                return False
            return age > 600  # an owner file is written right after mkdir
        if owner.get('host') == slurm.node_name() and isinstance(owner.get('pid'), int):
            # Same host: the owner process decides, whatever its job id (a killed worker of a running job, too).
            return not _pid_alive(owner['pid'])
        job = str(owner.get('job_id', ''))
        if job and not job.startswith('local-'):
            alive = slurm.is_job_alive(job)
            if alive is False:
                return True
            if alive is True:
                return False
        return self._heartbeat_age(owner) > LOCK_STALE_SECONDS

    def _mine(self, owner) -> bool:
        return isinstance(owner, dict) and all(owner.get(k) == self.owner[k] for k in ('pid', 'host', 'started_unix'))

    def _take(self):
        atomic_write_json(self.path / 'owner.json', self.owner)
        self.held = True
        self._start_heartbeat()

    def acquire(self):
        """Take the lock; returns None on success or the current owner dict when it is held."""
        self.path.parent.mkdir(parents=True, exist_ok=True)
        for _ in range(5):
            try:
                os.mkdir(self.path)
            except FileExistsError:
                owner = self._read_owner()
                if not self._stale(owner):
                    return owner or {'unknown': True}
                marker = self.path / 'takeover'
                try:
                    os.mkdir(marker)
                except FileNotFoundError:
                    continue  # released meanwhile: try the plain mkdir again
                except FileExistsError:
                    try:
                        if time.time() - marker.stat().st_mtime > TAKEOVER_STALE_SECONDS:
                            os.rmdir(marker)  # left by a contender that died during its takeover
                            continue
                    except OSError:
                        pass
                    return dict(owner or {'unknown': True}, takeover_in_progress=True)
                try:
                    again = self._read_owner()
                    if again != owner and again is not None and not self._stale(again):
                        return again  # another contender took it over first
                    self._take()
                    self.took_over = owner
                    return None
                finally:
                    try:
                        os.rmdir(marker)
                    except OSError:
                        pass
            else:
                self._take()
                return None
        return self._read_owner() or {'unknown': True}

    def _start_heartbeat(self):
        stop = threading.Event()
        self._beat_stop = stop
        path = self.path / 'owner.json'

        def beat():
            while not stop.wait(LOCK_HEARTBEAT_SECONDS):
                if not self._mine(self._read_owner()):
                    return
                try:
                    os.utime(path)
                except OSError:
                    pass

        threading.Thread(target=beat, name='corpus-lock-heartbeat', daemon=True).start()

    def release(self):
        if not self.held:
            return
        self.held = False
        if self._beat_stop is not None:
            self._beat_stop.set()
        if not self._mine(self._read_owner()):
            return  # taken over by another process: never remove its lock
        try:
            (self.path / 'owner.json').unlink()
        except OSError:
            pass
        try:
            os.rmdir(self.path)
        except OSError:
            pass


# --- reproducible gzip headers -------------------------------------------------------------------------------
class _FixedMtimeGzip:
    """Stand-in for the ``gzip`` module inside :func:`sources.prepare_bucket` (whose code stays verbatim):
    ``gzip.open(<name>.tmp, "wb")`` becomes ``gzip.GzipFile(<name>.tmp, "wb", 9, mtime=<recorded time>)``,
    which writes the same bytes except the header time.  Everything else is the real ``gzip`` module."""

    def __init__(self, mtimes: dict):
        self._mtimes = dict(mtimes)

    def __getattr__(self, name):
        return getattr(gzip, name)

    def open(self, filename, mode='rb', compresslevel=9, encoding=None, errors=None, newline=None):
        name = os.path.basename(os.fspath(filename)) if isinstance(filename, (str, bytes, os.PathLike)) else None
        if isinstance(name, bytes):
            name = name.decode()
        key = name[:-len('.tmp')] if name and name.endswith('.tmp') else name
        if mode == 'wb' and key in self._mtimes and self._mtimes[key] is not None:
            return gzip.GzipFile(filename, mode, compresslevel, mtime=self._mtimes[key])
        return gzip.open(filename, mode, compresslevel, encoding, errors, newline)


@contextlib.contextmanager
def fixed_gzip_mtime(mtimes: dict):
    """Within the block, files written by ``sources.prepare_bucket`` get the given header times."""
    saved = sources.gzip
    sources.gzip = _FixedMtimeGzip(mtimes)
    try:
        yield
    finally:
        sources.gzip = saved


def gzip_header_mtime(path) -> int:
    """Bytes 4-7 of a gzip file (little-endian header time)."""
    with open(path, 'rb') as handle:
        head = handle.read(8)
    return int.from_bytes(head[4:8], 'little')


