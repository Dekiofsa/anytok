"""Build the 23 corpus buckets on the cluster: ``$ANYTOK_ROOT/corpus/<size>-v1/<bucket>/``.

Replaces the Modal functions ``prepare`` / ``probe_sources`` / ``verify_corpus`` of
``scripts/modal_prepare_corpus.py`` (409-485); the bucket content comes from the verbatim port
:func:`hyak.corpus.sources.prepare_bucket`.  Pools are built to the **original pool targets**
(``full``, ``extra``, ``specialty``: 13.6 GB of raw training text plus 23 x 5 MB held-out text),
not just the recipe quota, so ``counts.train_bytes`` can be compared with the recipe's
``train_available_bytes``.

Usage (data environment; needs outbound HTTPS to huggingface.co)::

    python -m hyak.corpus.build [--sizes full extra specialty] [--buckets B ...] [--workers N]
    python -m hyak.corpus.build --probe              # first record of each of the ten sources
    python -m hyak.corpus.build --verify-only        # re-hash + recount every built bucket

Each bucket runs in its own child process (``--worker SIZE BUCKET``, internal), at most
``--workers`` (default ``HYAK_CORPUS_WORKERS``) at a time, largest buckets first.  Buckets are
independent, so the order of building cannot change any bucket's content.  A bucket whose
``manifest.json`` exists is verified (file hashes, document and byte recount, record format,
stopping rule, held-out rule) and skipped; a bucket that fails verification stops with a remedy
(it is never silently rebuilt).  A failed build deletes its temporary files and is retried
from zero up to ``--attempts`` times when the error looks transient (network, decompression);
deterministic errors (source exhausted, upstream file gone, encoding errors) are not retried.
A per-bucket lock directory keeps two jobs from writing the same bucket.

Status for the dashboard (``hyak-corpus``): ``<repo>/modal_results/hyak_tillicum/corpus/status.json``
+ ``events.jsonl`` (completed / 23 buckets, one worker row per running bucket, per-bucket bytes
under ``buckets``).  Per-bucket logs, progress, results and locks live in ``<corpus root>/.hyak/``.

Test-only miniature builds: ``--test-scale TRAIN_BYTES:EVAL_BYTES --corpus-root DIR`` replaces
the byte targets of every bucket, writes ``"test_scale": {...}`` into each manifest (marking it
non-production) and refuses the production corpus root.  ``hyak.corpus.stage_inputs`` rejects
such buckets unless its own ``--allow-test-scale`` flag is given.

Data environment: a production build refuses (exit 2) unless the installed versions of
``VALIDATED_PACKAGES`` (the set that reproduced every original anchor at full scale on 2026-11-13) are
installed, or ``--allow-unvalidated-env "<reason>"`` is given; the reason is recorded in every manifest
(``hyak.packages_validated`` / ``hyak.unvalidated_env_reason``) and in the ``build_start`` event.

Byte-reproducible rebuilds: the gzip header time (bytes 4-7) of both files of a bucket is chosen before
the build and recorded (manifest ``hyak.gzip_mtime`` and ``<corpus root>/.hyak/gzip-mtimes/<size>__<bucket>.json``).
A rebuild reuses a recorded time, so a lost or purged bucket is regenerated byte for byte (same SHA-256 as
``input/corpus/manifest.json``).  Order: ``--gzip-mtimes FILE`` (a ``{bucket: {"train.jsonl.gz": t,
"eval.jsonl.gz": t}}`` map or an ``input/manifest.json`` whose ``provenance.corpus.gzip_mtime`` holds it),
then ``$ANYTOK_ROOT/input/manifest.json`` (production corpus root only), then the corpus root's own record;
otherwise a production held-out file gets the ORIGINAL file's header time
(``hyak/corpus/reference/original_gzip_times.json``: the file is then the original byte for byte) and a
training file the build time.  The content is never affected.

Exit codes: 0 every selected bucket is complete, or the job stopped early for a benign reason
(job time limit, a bucket locked by another job; status ``paused`` says which); 4 a bucket failed
(build or verification; status ``failed`` names it and its log); 2 usage/configuration/environment error
(also: the source probe failed, or the data environment is not the validated one); 143 stopped by
SIGTERM/SIGINT (resubmit to continue; complete buckets are kept); 1 only for an unexpected crash
(traceback in the log).
"""
